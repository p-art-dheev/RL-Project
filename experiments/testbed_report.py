"""Real-AWS-testbed report: tables, paired statistics and a figure from the E8 runs.

  python -m experiments.testbed_report
Writes results/REAL_TESTBED.md and results/plots/e8_real.png.

Run sets (all interleaved per seed, 6-min runs, test-split jobs, PACE w = 0.9):
  results/testbed/            E8   static network estimates (calibration only)
  results/testbed/adaptive/   E8b  online network estimate, nominal load (rate_bc 0.075)
  results/testbed/adaptive_busy/  E8b  online network estimate, busy hour (rate_bc 0.15)
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.ticker import FixedLocator, FuncFormatter, NullLocator  # noqa: E402
import numpy as np  # noqa: E402
from scipy.stats import wilcoxon  # noqa: E402

ROOT = Path("results/testbed")
METHODS = [("pace", "PACE"), ("pace-shield", "PACE + shield"), ("mersem", "MERSEM-Balanced"),
           ("ca-eft", "CA-EFT"), ("eft", "EFT")]
COLORS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]  # fixed categorical order (validated)
MARKERS = ["o", "s", "^", "D", "v"]
LABEL_OFFSET = {(0, "pace"): (-40, -15), (0, "ca-eft"): (9, -4), (1, "pace"): (-14, 9),
                (1, "pace-shield"): (9, -13)}  # (panel, method) -> label offset in points, to avoid collisions
SETS = [("E8b nominal load (rate_bc 0.075)", ROOT / "adaptive"), ("E8b busy hour (rate_bc 0.15)", ROOT / "adaptive_busy"),
        ("E8 nominal, static estimates", ROOT)]


def load(folder: Path) -> dict:
    runs = {}
    for p in sorted(folder.glob("e8_*.json")):
        d = json.loads(p.read_text())
        runs.setdefault(d["args"]["scheduler"], {})[int(d["args"]["seed"])] = d["summary"]
    return runs


def row(rs: dict) -> dict:
    s = list(rs.values())
    m = lambda k: float(np.mean([x[k] for x in s]))  # noqa: E731
    return dict(n=len(s), A=100 * m("sla_A"), B=100 * m("sla_B"), AB=100 * m("sla_AB"), co2=m("carbon_dyn"),
                p95=m("p95_A"), seeds=[round(100 * rs[k]["sla_AB"], 1) for k in sorted(rs)],
                share="/".join(f"{100 * m(k):.0f}" for k in ("share_edge", "share_fog", "share_cloud")))


def main():
    data = {name: load(folder) for name, folder in SETS}
    lines = ["# PACE on the real AWS testbed (Coimbatore edge · Mumbai fog · Stockholm cloud)", "",
             "Generated by `python -m experiments.testbed_report` from the run files in `results/testbed/`. "
             "Every run: 6 minutes of the test-split workload on 2 laptop edge workers + 4 EC2 instances; schedulers "
             "interleaved per seed so they share network conditions; PACE = `models/pace_live.pt` at w = 0.9; "
             "MERSEM-Balanced (w_s = 0.5, 120 s epochs). Background and failure analysis: `testbed/E8_ANALYSIS.md`; "
             "predictions written before the runs: `testbed/TWIN_PREDICTION.md`; sim-to-real: `testbed/E9_SIM2REAL.md`.",
             "", "![E8b](plots/e8_real.png)", ""]
    for name, _folder in SETS:
        runs = data[name]
        lines += [f"## {name}", "", "| Scheduler | runs | alerts missed % | analytics missed % | A+B missed % | per seed A+B % | "
                  "carbon dyn (g) | p95 alert (s) | work edge/fog/cloud % |", "|---|---|---|---|---|---|---|---|---|"]
        for key, label in METHODS:
            if key in runs:
                r = row(runs[key])
                lines.append(f"| {label} | {r['n']} | {r['A']:.1f} | {r['B']:.1f} | **{r['AB']:.1f}** | "
                             f"{' / '.join(map(str, r['seeds']))} | {r['co2']:.4f} | {r['p95']:.2f} | {r['share']} |")
        lines.append("")
    lines.append("EFT in E8b nominal ran in a separate session after an orchestrator fix (its first runs are in "
                 "`testbed/invalid/`), so it is not interleaved with the other four.\n")

    # paired comparison over the 6 E8b seed-runs (3 nominal + 3 busy)
    lines += ["## Paired comparison over the six E8b runs (3 nominal + 3 busy)", "",
              "Δ = PACE variant minus baseline on the same seed and load (negative SLA Δ = PACE better). "
              "Wilcoxon signed-rank, two-sided; with 6 pairs the smallest attainable p is 0.031.", "",
              "| PACE variant | vs | better in | Δ A+B missed (pp) | p | Δ carbon dyn | p |", "|---|---|---|---|---|---|---|"]
    e8b = [data[SETS[0][0]], data[SETS[1][0]]]
    for a, al in (("pace", "PACE"), ("pace-shield", "PACE + shield")):
        for b, bl in (("mersem", "MERSEM-Balanced"), ("ca-eft", "CA-EFT")):
            ds, dc = [], []
            for runs in e8b:
                for seed in sorted(set(runs.get(a, {})) & set(runs.get(b, {}))):
                    x, y = runs[a][seed], runs[b][seed]
                    ds.append(100 * (x["sla_AB"] - y["sla_AB"]))
                    dc.append(x["carbon_dyn"] / y["carbon_dyn"] - 1)
            if len(ds) < 2:
                continue
            p1 = wilcoxon(ds).pvalue if any(ds) else 1.0
            p2 = wilcoxon(dc).pvalue if any(dc) else 1.0
            lines.append(f"| {al} | {bl} | {sum(d < 0 for d in ds)}/{len(ds)} | {np.mean(ds):+.1f} | {p1:.3f} | "
                         f"{100 * np.mean(dc):+.0f}% | {p2:.3f} |")
    lines += ["", "## Reading", "",
              "- **vs MERSEM (base paper):** PACE missed fewer deadlines in all six paired runs (−6.6 pp on "
              "average, p = 0.031), in both alerts and analytics, for +15 % operational carbon on average (not "
              "significant, p = 0.16). PACE + shield never missed an alert in the busy hour. At w = 0.9 PACE is "
              "configured to favour deadlines; MERSEM-Balanced sits at a lower-carbon, higher-miss point, so "
              "neither dominates on both axes in these runs.",
              "- **vs CA-EFT (strongest heuristic):** the same deadline performance (+0.2 pp, p = 0.88) with 15 % "
              "less carbon (p = 0.031).",
              "- **vs EFT:** EFT ignores carbon: 6× PACE's carbon at nominal load, and more missed deadlines.",
              "- **E8 → E8b:** without the online network estimate the evening network drift to Mumbai made the "
              "latency-estimate-driven schedulers (PACE, CA-EFT) miss alerts; with it they recover. "
              "E8 and E8b ran at different times, so this comparison is indicative.",
              "- **Limits:** 3 seeds per set, a campus network with four load-balanced uplinks, a lightly loaded "
              "testbed at nominal load (the carbon totals are small), and synthetic carbon-intensity profiles."]
    out = Path("results/REAL_TESTBED.md")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # figure: carbon vs deadline misses, one panel per E8b load (same axes scale type, separate charts)
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.3), sharey=False)
    for i, (ax, (name, _f)) in enumerate(zip(axes, SETS[:2])):
        runs = data[name]
        for (key, label), c, mk in zip(METHODS, COLORS, MARKERS):
            if key not in runs:
                continue
            seeds = list(runs[key].values())
            xs = [s["carbon_dyn"] for s in seeds]
            ys = [100 * s["sla_AB"] for s in seeds]
            ax.scatter(xs, ys, s=22, color=c, alpha=0.35, marker=mk, edgecolors="none")
            mx, my = float(np.mean(xs)), float(np.mean(ys))
            ax.scatter([mx], [my], s=90, color=c, marker=mk, edgecolors="white", linewidths=2, zorder=3, label=label)
            ax.annotate(label, (mx, my), xytext=LABEL_OFFSET.get((i, key), (8, 6)), textcoords="offset points",
                        fontsize=9, color="#333333")
        ax.set_xscale("log")
        ax.xaxis.set_major_locator(FixedLocator([0.03, 0.04, 0.05, 0.06, 0.08, 0.1, 0.15, 0.2, 0.3]))
        ax.xaxis.set_minor_locator(NullLocator())
        ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _p: f"{v:g}"))
        ax.set_title(name, fontsize=11, loc="left", color="#222222")
        ax.set_xlabel("operational carbon per run (g CO₂, log scale)  →  less is better", fontsize=9, color="#444444")
        ax.set_ylabel("deadlines missed, alerts + analytics (%)", fontsize=9, color="#444444")
        ax.grid(True, which="both", color="#e6e6e6", linewidth=0.6)
        ax.set_axisbelow(True)
        for sp in ("top", "right"):
            ax.spines[sp].set_visible(False)
        for sp in ("left", "bottom"):
            ax.spines[sp].set_color("#bbbbbb")
        ax.tick_params(colors="#555555", labelsize=8)
        ax.set_ylim(bottom=0)
    axes[0].legend(loc="upper left", fontsize=8, frameon=False)
    fig.suptitle("Real AWS testbed: big markers = mean of 3 seeds, small = individual seeds (lower-left is better)",
                 fontsize=10, color="#333333")
    fig.tight_layout()
    Path("results/plots").mkdir(parents=True, exist_ok=True)
    fig.savefig("results/plots/e8_real.png", dpi=150)
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
